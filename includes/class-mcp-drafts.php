<?php
/**
 * Drafts-only access level: a credential scope that may read everything,
 * create unpublished content and propose changes to live posts as draft copies.
 *
 * @package Cowboy_MCP
 */

defined( 'ABSPATH' ) || exit;

class Cowboy_MCP_Drafts {

    /** Statuses that count as unpublished. */
    const UNPUBLISHED = [ 'draft', 'pending', 'auto-draft' ];

    /** Statuses that count as live. */
    const LIVE = [ 'publish', 'future', 'private' ];

    /** Statuses a drafts credential may set. */
    const SETTABLE = [ 'draft', 'pending' ];

    /** Tools that create a post (status forced to a settable one by the gate). */
    const CREATE_TOOLS = [ 'wp_create_post' ];

    /** Other non-read-only tools a drafts credential may call. */
    const OTHER_ALLOWED = [ 'wp_upload_media', 'wp_batch_execute', 'wp_undo_change' ];

    /** Write tools that edit an existing post: tool => argument naming the target. */
    const WRITE_TARGETS = [
        'wp_update_post'                      => 'post_id',
        'wp_edit_blocks'                      => 'post_id',
        'wp_restore_revision'                 => 'revision_id',
        'wp_seo_update_meta'                  => 'post_id',
        'wp_acf_update_field'                 => 'object_id',
        'wp_acf_add_row'                      => 'object_id',
        'wp_acf_update_row'                   => 'object_id',
        'wp_beaver_update_layout'             => 'post_id',
        'wp_siteorigin_update_layout'         => 'post_id',
        'wp_siteorigin_edit_layout'           => 'post_id',
        'wp_siteorigin_apply_prebuilt_layout' => 'post_id',
    ];

    /** Read tools that take a target post: tool => argument. */
    const READ_TARGETS = [
        'wp_get_post'                  => 'post_id',
        'wp_list_blocks'               => 'post_id',
        'wp_seo_get_meta'              => 'post_id',
        'wp_acf_get_field'             => 'object_id',
        'wp_acf_get_fields'            => 'object_id',
        'wp_beaver_get_layout'         => 'post_id',
        'wp_siteorigin_get_layout'     => 'post_id',
        'wp_elementor_get_page_content' => 'post_id',
    ];

    /** Post types a drafts credential may never create or edit. */
    const DENIED_TYPES = [
        'product', 'product_variation', 'shop_order', 'shop_order_refund', 'shop_coupon',
        'nav_menu_item', 'wp_template', 'wp_template_part', 'wp_global_styles', 'wp_navigation',
        'wp_block', 'attachment', 'revision', 'customize_changeset', 'oembed_cache',
        'user_request', 'wp_font_family', 'wp_font_face',
    ];

    /** Types that are fine while unpublished but unsafe to copy or edit when live. */
    const LIVE_UNSAFE_TYPES = [ 'tribe_events', 'tribe_venue', 'tribe_organizer' ];

    /** Link meta: on the copy, the original's ID. */
    const META_COPY_OF = '_cowboy_mcp_draft_copy_of';

    /** Link meta: on the copy, the connection that made it. */
    const META_COPY_BY = '_cowboy_mcp_draft_copy_by';

    /** Link meta: on the copy, when it was made (GMT). */
    const META_COPY_AT = '_cowboy_mcp_draft_copy_at';

    /** Link meta: on the original, the copy's ID. */
    const META_COPY = '_cowboy_mcp_draft_copy';

    /** Option-name prefix of the per-original creation lock. */
    const LOCK_PREFIX = 'cowboy_mcp_draft_lock_';

    /** Meta never carried into a copy: volatile, internal, or regenerated by its plugin. */
    const SKIP_META = [
        '_edit_lock', '_edit_last', '_wp_old_slug', '_wp_old_date', '_encloseme', '_pingme',
        '_elementor_css', '_elementor_element_cache', '_elementor_page_assets',
    ];

    /** Meta key prefixes never carried into a copy (our link keys, Yoast Duplicate Post's markers). */
    const SKIP_META_PREFIXES = [ '_cowboy_mcp_draft_copy', '_dp_' ];

    /** Arguments that would change a live post's URL, date, author or status once the copy is republished. */
    const LIVE_FIXED_ARGS = [ 'status', 'slug', 'date', 'author' ];

    /** Bootstrap: keep the copy link consistent when a copy is deleted or republished. */
    public static function init(): void {
        add_action( 'before_delete_post', [ __CLASS__, 'on_delete_post' ] );
        add_action( 'duplicate_post_after_republish', [ __CLASS__, 'on_republish' ], 10, 2 );
    }

    /** A copy is being deleted: unlink it from its original (only where the original names this copy). */
    public static function on_delete_post( $post_id ): void {
        $post_id  = (int) $post_id;
        $original = self::original_of( $post_id );
        if ( $original < 1 ) {
            return;
        }
        if ( (int) get_post_meta( $original, self::META_COPY, true ) === $post_id ) {
            delete_post_meta( $original, self::META_COPY );
        }
        if ( (int) get_post_meta( $original, '_dp_has_rewrite_republish_copy', true ) === $post_id ) {
            delete_post_meta( $original, '_dp_has_rewrite_republish_copy' );
        }
    }

    /**
     * Yoast's Republish copies every meta key of the copy onto the original
     * (its own exclusion list only, filters off), our link keys included.
     * Strip them again, and unlink: the proposal has been applied.
     */
    public static function on_republish( $copy, $original ): void {
        if ( ! $copy instanceof WP_Post || ! $original instanceof WP_Post ) {
            return;
        }
        if ( (int) get_post_meta( $copy->ID, self::META_COPY_OF, true ) !== (int) $original->ID ) {
            return;
        }
        delete_post_meta( $original->ID, self::META_COPY_OF );
        delete_post_meta( $original->ID, self::META_COPY_BY );
        delete_post_meta( $original->ID, self::META_COPY_AT );
        if ( (int) get_post_meta( $original->ID, self::META_COPY, true ) === (int) $copy->ID ) {
            delete_post_meta( $original->ID, self::META_COPY );
        }
    }

    /** Whether the active credential is a drafts-only one. */
    public static function active(): bool {
        $scope = Cowboy_MCP_Security::current_scope();
        return null !== $scope && 'drafts' === ( $scope['mode'] ?? '' );
    }

    /**
     * Whether a drafts credential may call a tool at all. Inbound abilities
     * (names with a slash) count only when explicitly read-only.
     */
    public static function tool_allowed( string $name, array $annotations ): bool {
        if ( ! empty( $annotations['readOnlyHint'] ) ) {
            return true;
        }
        if ( str_contains( $name, '/' ) ) {
            return false;
        }
        return isset( self::WRITE_TARGETS[ $name ] )
            || in_array( $name, self::CREATE_TOOLS, true )
            || in_array( $name, self::OTHER_ALLOWED, true );
    }

    /**
     * Judge one call of a drafts credential before it runs.
     *
     * @return array{args: array, ctx: ?array, preview: ?array}|WP_Error
     */
    public static function gate( string $name, array $args ): array|WP_Error {
        $out = [ 'args' => $args, 'ctx' => null, 'preview' => null ];
        if ( ! self::active() ) {
            return $out;
        }

        if ( in_array( $name, self::CREATE_TOOLS, true ) ) {
            $checked = self::gate_create( $args );
            if ( is_wp_error( $checked ) ) {
                return $checked;
            }
            $out['args'] = $checked;
            return $out;
        }

        if ( isset( self::WRITE_TARGETS[ $name ] ) ) {
            return self::gate_target( $name, $args );
        }
        if ( isset( self::READ_TARGETS[ $name ] ) ) {
            return self::gate_read( $name, $args );
        }
        return $out;
    }

    /**
     * A read of a live post that has a draft copy returns the copy, so the AI reads the
     * version it edits (block and node paths line up). Never creates a copy; anything
     * that is not a post with a copy passes through untouched.
     */
    private static function gate_read( string $name, array $args ): array {
        $out = [ 'args' => $args, 'ctx' => null, 'preview' => null ];
        $arg = self::READ_TARGETS[ $name ];
        $raw = $args[ $arg ] ?? null;

        if ( 'wp_list_blocks' === $name && ( ! empty( $args['template'] ) || ! empty( $args['template_type'] ) ) ) {
            return $out; // A template read, not a post.
        }
        if ( str_starts_with( $name, 'wp_acf_' ) ) {
            $raw = self::acf_object_id( $raw );
        }
        if ( ! is_int( $raw ) && ! ( is_string( $raw ) && ctype_digit( $raw ) ) ) {
            return $out; // Options, terms, users, comments and the like.
        }
        $id = (int) $raw;
        if ( $id < 1 || ! get_post( $id ) ) {
            return $out;
        }

        $copy = self::find_copy( $id );
        if ( $copy ) {
            $args[ $arg ] = is_string( $args[ $arg ] ?? null ) ? (string) $copy->ID : (int) $copy->ID;
            $out['args']  = $args;
            $out['ctx']   = [
                'tool'            => $name,
                'copy_id'         => (int) $copy->ID,
                'original_id'     => $id,
                'original_status' => (string) ( get_post_status( $id ) ?: 'missing' ),
                'created'         => false,
                'read'            => true,
                'redirected'      => true,
            ];
            return $out;
        }
        $original = self::original_of( $id );
        if ( $original > 0 ) {
            $out['ctx'] = [
                'tool'            => $name,
                'copy_id'         => $id,
                'original_id'     => $original,
                'original_status' => (string) ( get_post_status( $original ) ?: 'missing' ),
                'created'         => false,
                'read'            => true,
                'redirected'      => false,
            ];
        }
        return $out;
    }

    /** Normalise and judge a requested status (as the handlers read it). */
    private static function gate_status( array $args ): array|WP_Error {
        if ( ! array_key_exists( 'status', $args ) || null === $args['status'] ) {
            return $args;
        }
        $status = is_scalar( $args['status'] ) ? sanitize_key( (string) $args['status'] ) : '';
        if ( ! in_array( $status, self::SETTABLE, true ) ) {
            return new WP_Error( 'drafts_status', 'This credential is drafts-only: status must be draft or pending. A person publishes from wp-admin.' );
        }
        $args['status'] = $status;
        return $args;
    }

    /** Every tag must already exist: creating terms changes the live taxonomy. */
    private static function gate_tags( array $args ): ?WP_Error {
        if ( ! isset( $args['tags'] ) || ! is_array( $args['tags'] ) ) {
            return null;
        }
        foreach ( $args['tags'] as $tag ) {
            $tag = is_scalar( $tag ) ? sanitize_text_field( (string) $tag ) : '';
            if ( '' === $tag || ! term_exists( $tag, 'post_tag' ) ) {
                return new WP_Error( 'drafts_new_tag', 'This credential is drafts-only: tag "' . $tag . '" does not exist and creating terms is not allowed. Use an existing tag or leave tags out.' );
            }
        }
        return null;
    }

    /** An ACF object_id judged exactly as the handler normalizes it (an int for a post ID). */
    private static function acf_object_id( $raw ) {
        if ( ! is_string( $raw ) ) {
            return $raw;
        }
        return function_exists( 'cowboy_mcp_acf_normalize_object_id' )
            ? cowboy_mcp_acf_normalize_object_id( $raw )
            : ( ctype_digit( $raw ) ? (int) $raw : $raw );
    }

    private static function type_error( string $type ): ?WP_Error {
        if ( in_array( $type, self::DENIED_TYPES, true ) ) {
            return new WP_Error( 'drafts_post_type', "This credential is drafts-only: post type {$type} is not available. It is site-wide configuration, not content." );
        }
        return null;
    }

    private static function gate_create( array $args ): array|WP_Error {
        if ( ! array_key_exists( 'status', $args ) || null === $args['status'] ) {
            $args['status'] = 'draft';
        }
        $args = self::gate_status( $args );
        if ( is_wp_error( $args ) ) {
            return $args;
        }
        $type = isset( $args['post_type'] ) && is_scalar( $args['post_type'] ) ? sanitize_key( (string) $args['post_type'] ) : 'post';
        $obj  = post_type_exists( $type ) ? get_post_type_object( $type ) : null;
        if ( ! $obj || empty( $obj->show_ui ) ) {
            return new WP_Error( 'drafts_post_type', "This credential is drafts-only: post type {$type} does not exist or is not editable content. Use post, page or another content type." );
        }
        $err = self::type_error( $type );
        if ( $err ) {
            return $err;
        }
        $err = self::gate_tags( $args );
        return $err ? $err : $args;
    }

    private static function gate_target( string $name, array $args ): array|WP_Error {
        $out = [ 'args' => $args, 'ctx' => null, 'preview' => null ];
        $arg = self::WRITE_TARGETS[ $name ];
        $raw = $args[ $arg ] ?? null;

        if ( str_starts_with( $name, 'wp_acf_' ) ) {
            $norm = self::acf_object_id( $raw );
            if ( ! is_int( $norm ) || $norm < 1 ) {
                return new WP_Error( 'drafts_acf_target', 'This credential is drafts-only: ACF writes to options, terms, users and comments change the live site. Pass the numeric ID of a draft post as object_id (digits only, no spaces).' );
            }
            $raw = $norm;
        }
        if ( 'wp_edit_blocks' === $name && ( ! empty( $args['template'] ) || ! empty( $args['template_type'] ) ) ) {
            return new WP_Error( 'drafts_template', 'This credential is drafts-only: block templates are site-wide. Edit a post by post_id instead.' );
        }

        $id   = (int) $raw;
        $post = $id > 0 ? get_post( $id ) : null;
        if ( ! $post ) {
            return $out; // The handler reports not-found.
        }

        if ( 'wp_restore_revision' === $name ) {
            if ( 'revision' !== $post->post_type ) {
                return $out; // The handler refuses a non-revision.
            }
            $parent = $post->post_parent ? get_post( (int) $post->post_parent ) : null;
            if ( ! $parent ) {
                return $out;
            }
            if ( in_array( $parent->post_status, self::LIVE, true ) ) {
                return new WP_Error( 'drafts_live_revision', 'Restoring a revision of a live post is not possible on a drafts-only connection. Read it with wp_get_revision_diff and apply the change with wp_update_post; it will be saved to a draft copy.' );
            }
            $post = $parent;
        }

        $err = self::type_error( $post->post_type );
        if ( $err ) {
            return $err;
        }
        if ( in_array( $post->post_status, self::LIVE, true ) ) {
            return self::gate_live( $name, $args, $arg, $post );
        }
        if ( ! in_array( $post->post_status, self::UNPUBLISHED, true ) ) {
            $label = 'trash' === $post->post_status ? 'in the trash' : 'not a draft';
            return new WP_Error( 'drafts_status_target', "Post {$post->ID} is {$label} (status: {$post->post_status}); a drafts-only connection can only edit drafts and propose changes to live posts." );
        }
        if ( array_key_exists( 'post_type', $args ) && null !== $args['post_type'] ) {
            $type = is_scalar( $args['post_type'] ) ? sanitize_key( (string) $args['post_type'] ) : '';
            $obj  = post_type_exists( $type ) ? get_post_type_object( $type ) : null;
            if ( ! $obj || empty( $obj->show_ui ) ) {
                return new WP_Error( 'drafts_post_type', "This credential is drafts-only: post type {$type} does not exist or is not editable content." );
            }
            $err = self::type_error( $type );
            if ( $err ) {
                return $err;
            }
        }

        // A copy addressed by its own ID is edited in place, but a Republish writes its
        // author, date, parent and type onto the live original: same refusals as via the original.
        $original = 'wp_restore_revision' === $name ? 0 : self::original_of( $post->ID );
        if ( $original > 0 ) {
            $err = self::live_field_error( $args, $post, true, "Post {$post->ID} is a draft copy of live post {$original}." );
            if ( $err ) {
                return $err;
            }
        }

        $args = self::gate_status( $args );
        if ( is_wp_error( $args ) ) {
            return $args;
        }
        $err = self::gate_tags( $args );
        if ( $err ) {
            return $err;
        }
        $out['args'] = $args;

        if ( $original > 0 ) {
            $out['ctx'] = [
                'tool'            => $name,
                'copy_id'         => (int) $post->ID,
                'original_id'     => $original,
                'original_status' => (string) ( get_post_status( $original ) ?: 'missing' ),
                'created'         => false,
            ];
        }
        return $out;
    }

    /**
     * Fields a Republish would carry onto the live post's URL, date, author or status.
     * $post is the live original or its copy (Yoast's Republish clones the copy and
     * keeps only the original's ID, post_name and status). On a copy, status may be
     * draft or pending (gate_status() judges it); on a live post it is refused.
     */
    private static function live_field_error( array $args, WP_Post $post, bool $is_copy, string $what ): ?WP_Error {
        $fixed = $is_copy ? array_diff( self::LIVE_FIXED_ARGS, [ 'status' ] ) : self::LIVE_FIXED_ARGS;
        foreach ( $fixed as $key ) {
            if ( array_key_exists( $key, $args ) && null !== $args[ $key ] ) {
                return new WP_Error( 'drafts_live_field', "{$what} Setting {$key} would change the live post's URL, date, author or status, so a drafts-only connection cannot propose it. Leave {$key} out; the rest of the change goes to the draft copy." );
            }
        }
        if ( array_key_exists( 'parent', $args ) && null !== $args['parent'] && (int) $args['parent'] !== (int) $post->post_parent ) {
            return new WP_Error( 'drafts_live_field', "{$what} Changing parent would change the live post's URL once the copy is published, so a drafts-only connection cannot propose it. Leave parent out." );
        }
        if ( array_key_exists( 'post_type', $args ) && null !== $args['post_type']
            && ( is_scalar( $args['post_type'] ) ? sanitize_key( (string) $args['post_type'] ) : '' ) !== $post->post_type ) {
            return new WP_Error( 'drafts_live_field', "{$what} Changing post_type would change the live post's URL once the copy is published, so a drafts-only connection cannot propose it. Leave post_type out." );
        }
        return null;
    }

    /**
     * A live target: refuse what a copy cannot carry or would carry back wrongly,
     * then point the call at the post's draft copy (made on first use).
     */
    private static function gate_live( string $name, array $args, string $arg, WP_Post $post ): array|WP_Error {
        $id  = (int) $post->ID;
        $err = self::live_field_error( $args, $post, false, "Post {$id} is live." );
        if ( $err ) {
            return $err;
        }
        if ( in_array( $post->post_type, self::LIVE_UNSAFE_TYPES, true ) ) {
            return new WP_Error( 'drafts_live_type', "Post {$id} is a live {$post->post_type}, whose data lives in custom tables a draft copy cannot carry. A drafts-only connection can only edit unpublished ones; ask the owner to make this change." );
        }
        if ( 'wp_seo_update_meta' === $name ) {
            if ( class_exists( 'Cowboy_MCP_Tools' ) ) {
                Cowboy_MCP_Tools::boot_domains();
            }
            if ( function_exists( 'cowboy_mcp_seo_get_provider' ) && 'aioseo' === ( cowboy_mcp_seo_get_provider()['provider'] ?? '' ) ) {
                return new WP_Error( 'drafts_live_seo', "Post {$id} is live, and All in One SEO keeps its SEO data in its own table, which a draft copy cannot carry back. A drafts-only connection can only change AIOSEO data on unpublished posts; ask the owner to make this change." );
            }
        }
        $err = self::gate_tags( $args );
        if ( $err ) {
            return $err;
        }

        if ( ! empty( $args['dry_run'] ) ) {
            $existing = self::find_copy( $id );
            $changes  = $args;
            unset( $changes[ $arg ], $changes['dry_run'], $changes['confirm'] );
            $preview = [
                'dry_run'    => true,
                'tool'       => $name,
                'would'      => $existing ? "save to draft copy {$existing->ID}" : "create a draft copy of post {$id} and save there",
                'draft_copy' => self::describe( [
                    'copy_id'         => $existing ? (int) $existing->ID : null,
                    'original_id'     => $id,
                    'original_status' => $post->post_status,
                    'created'         => ! $existing,
                ] ),
                'changes'    => (object) $changes,
                'note'       => "Post {$id} is live, so this change would be saved to a draft copy for the owner to review and publish. The live post would be unchanged.",
            ];
            return [
                'args'    => $args,
                'ctx'     => null,
                'preview' => [
                    'content' => [ [ 'type' => 'text', 'text' => (string) wp_json_encode( $preview, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES ) ] ],
                ],
            ];
        }

        $got = self::copy_for( $post );
        if ( is_wp_error( $got ) ) {
            return $got;
        }
        $copy_id      = (int) $got['copy']->ID;
        $args[ $arg ] = is_string( $args[ $arg ] ?? null ) ? (string) $copy_id : $copy_id;
        $ctx          = [
            'tool'            => $name,
            'copy_id'         => $copy_id,
            'original_id'     => $id,
            'original_status' => $post->post_status,
            'created'         => (bool) $got['created'],
        ];
        if ( $got['created'] ) {
            // The CREATE row's hash is the copy as made, before this call's edit: undoing
            // that edit and then the creation must not conflict.
            $ctx['created_hash'] = Cowboy_MCP_Rollback::draft_copy_hash( Cowboy_MCP_Rollback::snapshot( 'post', (string) $copy_id ) );
        }
        return [ 'args' => $args, 'ctx' => $ctx, 'preview' => null ];
    }

    /** The draft_copy block of a result. */
    private static function describe( array $ctx ): array {
        $copy_id = isset( $ctx['copy_id'] ) ? (int) $ctx['copy_id'] : null;
        return [
            'copy_id'         => $copy_id,
            'original_id'     => (int) $ctx['original_id'],
            'original_status' => (string) $ctx['original_status'],
            'created'         => (bool) $ctx['created'],
            'edit_url'        => $copy_id ? admin_url( 'post.php?post=' . $copy_id . '&action=edit' ) : '',
        ];
    }

    /**
     * The original's draft copy, if it still is one: it exists, is still draft or
     * pending, and links back to the original.
     */
    public static function find_copy( int $original_id ): ?WP_Post {
        $copy_id = (int) get_post_meta( $original_id, self::META_COPY, true );
        if ( $copy_id < 1 || $copy_id === $original_id ) {
            return null;
        }
        $copy = get_post( $copy_id );
        if ( ! $copy || ! in_array( $copy->post_status, self::SETTABLE, true ) ) {
            return null;
        }
        return (int) get_post_meta( $copy_id, self::META_COPY_OF, true ) === $original_id ? $copy : null;
    }

    /** The ID of the post this one is a draft copy of; 0 when it is not a copy. */
    public static function original_of( int $copy_id ): int {
        $original = $copy_id > 0 ? (int) get_post_meta( $copy_id, self::META_COPY_OF, true ) : 0;
        return $original > 0 && $original !== $copy_id ? $original : 0;
    }

    /**
     * Find or make the original's draft copy.
     *
     * Creation runs under a per-original lock row in the options table, so two
     * calls at the same moment make one copy. The row is written with INSERT
     * IGNORE: add_option() writes INSERT … ON DUPLICATE KEY UPDATE, which lets a
     * second request "succeed" whenever the stored value differs (a later second).
     *
     * @return array{copy: WP_Post, created: bool}|WP_Error
     */
    public static function copy_for( WP_Post $original ): array|WP_Error {
        $id       = (int) $original->ID;
        $existing = self::find_copy( $id );
        if ( $existing ) {
            return [ 'copy' => $existing, 'created' => false ];
        }

        $lock = self::LOCK_PREFIX . $id;
        $held = self::lock( $lock );
        for ( $i = 0; ! $held && $i < 20; $i++ ) {
            usleep( 100000 );
            wp_cache_delete( $id, 'post_meta' );
            $existing = self::find_copy( $id );
            if ( $existing ) {
                return [ 'copy' => $existing, 'created' => false ];
            }
            $held = self::lock( $lock );
        }
        if ( ! $held ) {
            return new WP_Error( 'drafts_copy_busy', "Another request is creating the draft copy of post {$id}. Try again in a moment." );
        }

        try {
            // Another request may have finished a copy between our first look and the lock.
            wp_cache_delete( $id, 'post_meta' );
            $existing = self::find_copy( $id );
            if ( $existing ) {
                return [ 'copy' => $existing, 'created' => false ];
            }
            $copy = self::create_copy( $original );
            return is_wp_error( $copy ) ? $copy : [ 'copy' => $copy, 'created' => true ];
        } finally {
            global $wpdb;
            // phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching,PluginCheck.Security.DirectDB.UnescapedDBParameter
            $wpdb->delete( $wpdb->options, [ 'option_name' => $lock ], [ '%s' ] );
        }
    }

    /** Take the lock row; a lock older than 30 s is taken over. */
    private static function lock( string $name ): bool {
        global $wpdb;
        $now = time();
        // phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching,PluginCheck.Security.DirectDB.UnescapedDBParameter
        $ok = $wpdb->query( $wpdb->prepare( "INSERT IGNORE INTO %i (option_name, option_value, autoload) VALUES (%s, %s, 'no')", $wpdb->options, $name, (string) $now ) );
        if ( 1 === $ok ) {
            return true;
        }
        // phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching,PluginCheck.Security.DirectDB.UnescapedDBParameter
        $since = $wpdb->get_var( $wpdb->prepare( "SELECT option_value FROM %i WHERE option_name = %s", $wpdb->options, $name ) );
        if ( null !== $since && $now - (int) $since > 30 ) {
            // Compare-and-delete: only the stale value, so two takers cannot both win.
            // phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching,PluginCheck.Security.DirectDB.UnescapedDBParameter
            $wpdb->delete( $wpdb->options, [ 'option_name' => $name, 'option_value' => $since ], [ '%s', '%s' ] );
            // phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching,PluginCheck.Security.DirectDB.UnescapedDBParameter
            return 1 === $wpdb->query( $wpdb->prepare( "INSERT IGNORE INTO %i (option_name, option_value, autoload) VALUES (%s, %s, 'no')", $wpdb->options, $name, (string) $now ) );
        }
        return false;
    }

    private static function skip_meta( string $key ): bool {
        if ( in_array( $key, self::SKIP_META, true ) ) {
            return true;
        }
        foreach ( self::SKIP_META_PREFIXES as $prefix ) {
            if ( str_starts_with( $key, $prefix ) ) {
                return true;
            }
        }
        return false;
    }

    /** Whether the original already has a Rewrite & Republish copy a person made in Yoast. */
    private static function has_person_yoast_copy( int $original_id ): bool {
        $named = (int) get_post_meta( $original_id, '_dp_has_rewrite_republish_copy', true );
        if ( $named < 1 || ! get_post( $named ) ) {
            return false;
        }
        return (int) get_post_meta( $named, self::META_COPY_OF, true ) !== $original_id;
    }

    /** Make the copy: fields, terms, meta, our link, and Yoast's markers when they apply. */
    private static function create_copy( WP_Post $o ): WP_Post|WP_Error {
        $copy_id = wp_insert_post( wp_slash( [
            'post_type'      => $o->post_type,
            'post_status'    => 'draft',
            'post_title'     => $o->post_title,
            'post_content'   => $o->post_content,
            'post_excerpt'   => $o->post_excerpt,
            'post_parent'    => (int) $o->post_parent,
            'menu_order'     => (int) $o->menu_order,
            'comment_status' => $o->comment_status,
            'ping_status'    => $o->ping_status,
            'post_password'  => $o->post_password,
            // Republish writes these back too: a blank one would erase stored source (e.g. Markdown).
            'post_content_filtered' => $o->post_content_filtered,
            'post_mime_type' => $o->post_mime_type,
            // Republish writes these back onto the original: they must be the original's.
            'post_author'    => (int) $o->post_author,
            'post_date'      => $o->post_date,
            'post_date_gmt'  => $o->post_date_gmt,
            'post_name'      => '',
        ] ), true );
        if ( is_wp_error( $copy_id ) ) {
            return $copy_id;
        }
        $copy_id = (int) $copy_id;
        try {
            self::fill_copy( $o, $copy_id );
        } catch ( \Throwable $e ) {
            wp_delete_post( $copy_id, true ); // never leave a half-made copy behind
            return new WP_Error( 'drafts_copy_failed', "Could not create a draft copy of post {$o->ID}: " . $e->getMessage() );
        }
        clean_post_cache( $copy_id );
        $copy = get_post( $copy_id );
        return $copy ? $copy : new WP_Error( 'drafts_copy_failed', "Could not create a draft copy of post {$o->ID}." );
    }

    /** Terms, meta, link and Yoast markers of a freshly inserted copy. */
    private static function fill_copy( WP_Post $o, int $copy_id ): void {
        foreach ( get_object_taxonomies( $o->post_type ) as $tax ) {
            $ids = wp_get_object_terms( $o->ID, $tax, [ 'fields' => 'ids' ] );
            wp_set_object_terms( $copy_id, is_wp_error( $ids ) ? [] : array_map( 'intval', $ids ), $tax );
        }

        foreach ( get_post_meta( $o->ID ) as $key => $values ) {
            $key = (string) $key;
            if ( self::skip_meta( $key ) ) {
                continue;
            }
            delete_post_meta( $copy_id, $key ); // a save_post hook may already have added it
            foreach ( (array) $values as $raw ) {
                add_post_meta( $copy_id, $key, Cowboy_MCP_Rollback::slash_deep( maybe_unserialize( $raw ) ) );
            }
        }

        $ctx = class_exists( 'Cowboy_MCP_Auth' ) ? Cowboy_MCP_Auth::$current_key_context : [];
        $by  = (string) ( ( $ctx['key_label'] ?? '' ) ?: ( $ctx['key_id'] ?? '' ) );
        update_post_meta( $copy_id, self::META_COPY_OF, (int) $o->ID );
        update_post_meta( $copy_id, self::META_COPY_BY, wp_slash( $by ) );
        update_post_meta( $copy_id, self::META_COPY_AT, gmdate( 'Y-m-d H:i:s' ) );
        update_post_meta( $o->ID, self::META_COPY, $copy_id );

        // 4.6 added duplicate_post_after_republish, which on_republish() needs to strip our links again.
        if ( defined( 'DUPLICATE_POST_CURRENT_VERSION' ) && version_compare( (string) DUPLICATE_POST_CURRENT_VERSION, '4.6', '>=' )
            && 'publish' === $o->post_status && ! self::has_person_yoast_copy( (int) $o->ID ) ) {
            update_post_meta( $copy_id, '_dp_original', (int) $o->ID );
            update_post_meta( $copy_id, '_dp_is_rewrite_republish_copy', 1 );
            update_post_meta( $copy_id, '_dp_creation_date_gmt', current_time( 'mysql', 1 ) );
            update_post_meta( $o->ID, '_dp_has_rewrite_republish_copy', $copy_id );
        }
    }

    /**
     * After a successful handler (before the edit's own journal row): journal a
     * copy made in this call as a post CREATE, audit it, and tell the agent
     * where the change went.
     */
    public static function after_success( ?array $ctx, mixed $result ): mixed {
        if ( null === $ctx ) {
            return $result;
        }
        $copy_id     = (int) $ctx['copy_id'];
        $original_id = (int) $ctx['original_id'];

        if ( ! empty( $ctx['created'] ) ) {
            if ( class_exists( 'Cowboy_MCP_Rollback' ) && ! empty( Cowboy_MCP_Tools::get_settings()['undo_enabled'] ?? true ) ) {
                $after = Cowboy_MCP_Rollback::snapshot( 'post', (string) $copy_id );
                Cowboy_MCP_Rollback::insert_row( [
                    'tool'         => 'wp_create_post',
                    'action'       => 'create',
                    'object_type'  => 'post',
                    'object_id'    => (string) $copy_id,
                    'object_label' => $after['post']['post_title'] ?? "post #{$copy_id}",
                    'before_state' => null,
                    'after_hash'   => (string) ( $ctx['created_hash'] ?? Cowboy_MCP_Rollback::draft_copy_hash( $after ) ),
                ] );
            }
            if ( class_exists( 'Cowboy_MCP_Auth' ) ) {
                Cowboy_MCP_Auth::log( 'draft_copy_created', array_merge( Cowboy_MCP_Auth::$current_key_context, [
                    'tool'          => (string) ( $ctx['tool'] ?? '' ),
                    'args'          => [ 'original_id' => $original_id, 'copy_id' => $copy_id ],
                    'result_status' => 'success',
                ] ) );
            }
        }

        if ( ! empty( $ctx['read'] ) ) {
            $note = self::read_note( $ctx );
            if ( is_string( $result ) ) {
                return $result . "\n" . $note;
            }
            if ( ! is_array( $result ) ) {
                return $result;
            }
            $result['draft_copy'] = self::describe( $ctx );
            $result['note']       = isset( $result['note'] ) && is_string( $result['note'] ) && '' !== $result['note']
                ? $note . ' ' . $result['note']
                : $note;
            return $result;
        }

        $note = in_array( (string) $ctx['original_status'], self::LIVE, true )
            ? "Post {$original_id} is live, so this change was saved to draft copy {$copy_id} for the owner to review and publish. The live post is unchanged."
            : "Post {$copy_id} is a draft copy of post {$original_id}, which is no longer live (status: {$ctx['original_status']}). The change was saved to the copy.";
        if ( is_string( $result ) ) {
            return $result . "\n" . $note;
        }
        if ( ! is_array( $result ) ) {
            return $result;
        }
        $result['draft_copy'] = self::describe( $ctx );
        $result['note']       = isset( $result['note'] ) && is_string( $result['note'] ) && '' !== $result['note']
            ? $note . ' ' . $result['note']
            : $note;
        return $result;
    }

    /**
     * What a drafts-only connection may not undo (called from Rollback::undo_policy()).
     * Allowed only for this connection's own change (the row's key_id) to a post that
     * is still unpublished, or the creation of one that no longer exists, when the
     * restore would not set a live status. Never forced: force skips the conflict
     * check, the only thing that notices a person's later (unjournaled) edits. A redo
     * that would re-create a removed draft copy is refused: it would come back unlinked.
     */
    public static function undo_block( array $row, bool $force = false ): ?WP_Error {
        if ( $force ) {
            return new WP_Error( 'drafts_undo_force', 'A drafts-only connection cannot force an undo: forcing would overwrite or delete changes made since, possibly by a person. Undo the later change first, or pass both change ids in change_ids (they are undone newest first).' );
        }
        $deny = new WP_Error( 'drafts_undo', 'A drafts-only connection can only undo its own changes to drafts.' );
        $ctx  = class_exists( 'Cowboy_MCP_Auth' ) ? Cowboy_MCP_Auth::$current_key_context : [];
        $mine = substr( (string) ( $ctx['key_id'] ?? '' ), 0, 64 ); // the journal column is 64 wide
        if ( '' === $mine || (string) ( $row['key_id'] ?? '' ) !== $mine ) {
            return $deny;
        }

        $state   = is_array( $row['before_state'] ?? null ) ? $row['before_state'] : null;
        $copy_of = (int) ( $state['_volatile']['draft_copy_of'] ?? 0 );
        if ( 'wp_undo_change' === ( $row['tool'] ?? '' ) && $copy_of > 0 ) {
            return new WP_Error( 'drafts_undo_copy_redo', "Change #{$row['id']} would re-create draft copy {$row['object_id']} of post {$copy_of}, which an undo removed. It would come back unlinked from post {$copy_of}, so a drafts-only connection cannot redo it. Edit post {$copy_of} again instead: the change goes to a new draft copy." );
        }

        // The post the row restores, as each strategy the drafts tools journal stores it.
        $type   = (string) ( $row['object_type'] ?? '' );
        $object = (string) ( $row['object_id'] ?? '' );
        if ( 'acf_value' === $type ) {
            // field@object, split as restore() does; the object judged as the gate judges it.
            $object  = self::acf_object_id( explode( '@', $object, 2 )[1] ?? '' );
            $post_id = is_int( $object ) ? $object : 0;
        } elseif ( 'post' === $type || 'seo_row' === $type ) {
            $post_id = ctype_digit( $object ) ? (int) $object : 0;
        } else {
            return $deny;
        }
        if ( $post_id < 1 ) {
            return $deny;
        }

        $post = get_post( $post_id );
        if ( $post ) {
            if ( ! in_array( $post->post_status, self::UNPUBLISHED, true ) || self::type_error( $post->post_type ) ) {
                return $deny;
            }
        } elseif ( 'create' !== ( $row['action'] ?? '' ) ) {
            return $deny;
        }
        $before = $state['post'] ?? null;
        if ( is_array( $before ) ) {
            if ( isset( $before['post_status'] ) && ! in_array( (string) $before['post_status'], self::UNPUBLISHED, true ) ) {
                return $deny;
            }
            if ( isset( $before['post_type'] ) && self::type_error( (string) $before['post_type'] ) ) {
                return $deny;
            }
        }
        return null;
    }

    /** The note a read adds: which post the result shows, and whether the original is live. */
    private static function read_note( array $ctx ): string {
        $copy_id     = (int) $ctx['copy_id'];
        $original_id = (int) $ctx['original_id'];
        $status      = (string) $ctx['original_status'];
        $live        = in_array( $status, self::LIVE, true );
        if ( ! empty( $ctx['redirected'] ) ) {
            return $live
                ? "Post {$original_id} is live and has a draft copy; this shows draft copy {$copy_id}. The live post is unchanged."
                : "Post {$original_id} is no longer live (status: {$status}) and has a draft copy; this shows draft copy {$copy_id}.";
        }
        return "Post {$copy_id} is a draft copy of post {$original_id}"
            . ( $live ? ', which is live. The live post is unchanged.' : ", which is no longer live (status: {$status})." );
    }

    /** The draft_copy block and note a read adds, for readers that do not go through call_tool(). */
    public static function read_flag( int $original_id, int $copy_id, bool $redirected = true ): array {
        $ctx = [
            'copy_id'         => $copy_id,
            'original_id'     => $original_id,
            'original_status' => (string) ( get_post_status( $original_id ) ?: 'missing' ),
            'created'         => false,
            'redirected'      => $redirected,
        ];
        return [ 'draft_copy' => self::describe( $ctx ), 'note' => self::read_note( $ctx ) ];
    }

    /** The call failed: permanently delete a copy it created (the delete hook unlinks the original). */
    public static function abandon( ?array $ctx ): void {
        if ( null === $ctx || empty( $ctx['created'] ) || empty( $ctx['copy_id'] ) ) {
            return;
        }
        wp_delete_post( (int) $ctx['copy_id'], true );
    }
